#!/usr/bin/env python3
"""rel_build.py — every Mario Party 4 overlay (src/REL/<name>) compiled INTO the one web module.

Party Board builds each overlay as its own shared library and objdll.c dlopen()s it. The web build is
one module (Emscripten's dlopen never unloads, so a second visit would keep the first visit's statics),
so this reproduces what an overlay link means, the same way gamecube/recomp/ovl_build.py does for the
recomp:
  1. NAMESPACE: every global an overlay DEFINES is renamed with a per-overlay prefix (a generated
     `-include` header of `#define sym prefix_sym`, found with llvm-nm after a first compile).
  2. FRESH STATICS ON EVERY LINK: each overlay's objects sit between two marker objects, so its .data
     and .bss are one contiguous range each; src/rel_dispatch.c snapshots .data on the first link and
     restores it, and zeroes .bss, on every later one — what dlopen of a fresh library gives natively.
usage: rel_build.py BUILD PB_SRC CFLAGS_FILE   (writes BUILD/rel/link_order.txt and BUILD/rel/rel_table.c)
"""
import os, re, subprocess, sys, glob

BUILD, PB, CFF = sys.argv[1], sys.argv[2], sys.argv[3]
O = os.path.join(BUILD, 'rel'); OBJ = os.path.join(O, 'obj'); os.makedirs(OBJ, exist_ok=True)
CFLAGS = [l.rstrip('\n') for l in open(CFF) if l.strip()]
EMCC = os.environ.get('EMCC', 'emcc')
NM = os.environ.get('LLVM_NM', os.path.expanduser('~/emsdk-upstream/upstream/bin/llvm-nm'))
REL = os.path.join(PB, 'src', 'REL')
EXCLUDED = {'nisDll', 'safDll'}

def run(cmd):
    return subprocess.run(cmd, capture_output=True, text=True)

def objname(prefix, u):
    rel = os.path.relpath(u, REL).replace('/', '_')
    return os.path.join(OBJ, prefix + '__' + rel[:-2] + '.o')

def compile_units(prefix, units, extra):
    errs = []
    for u in units:
        o = objname(prefix, u)
        r = run([EMCC] + CFLAGS + extra + ['-c', u, '-o', o])
        if r.returncode:
            errs.append('%s: %s' % (u, r.stderr[-600:]))
    return errs

def defined_globals(objs):
    syms = set()
    for o in objs:
        r = run([NM, '--defined-only', '--extern-only', '-j', o])
        for s in r.stdout.split():
            if s and not s.startswith('__ovl_'):
                syms.add(s)
    return sorted(syms)

table, link_order, problems = [], [], 0
for d in sorted(os.listdir(REL)):
    if d in EXCLUDED or not os.path.isdir(os.path.join(REL, d)):
        continue
    units = sorted(glob.glob(os.path.join(REL, d, '**', '*.c'), recursive=True))
    if not units:
        continue
    if re.match(r'^w..Dll$', d):
        units.append(os.path.join(REL, 'board_executor.c'))
    prefix = 'rel_' + d.lower()
    errs = compile_units(prefix, units, [])
    if errs:
        print('[rel] FAIL %s (first pass): %s' % (d, errs[0][:500])); problems += 1; continue
    syms = defined_globals([objname(prefix, u) for u in units])
    if 'ObjectSetup' not in syms:
        print('[rel] FAIL %s: no ObjectSetup' % d); problems += 1; continue
    hdr = os.path.join(O, prefix + '_rename.h')
    with open(hdr, 'w') as f:
        for s in syms:
            f.write('#define %s %s_%s\n' % (s, prefix, s))
    errs = compile_units(prefix, units, ['-include', hdr])
    if errs:
        print('[rel] FAIL %s (renamed): %s' % (d, errs[0][:500])); problems += 1; continue
    for side in ('b', 'e'):
        src = os.path.join(O, '%s_mark_%s.c' % (prefix, side))
        with open(src, 'w') as f:
            f.write('char __%s_data_%s[1] = {1};\nchar __%s_bss_%s[1];\n' % (prefix, side, prefix, side))
        r = run([EMCC] + CFLAGS + ['-c', src, '-o', src[:-2] + '.o'])
        if r.returncode:
            sys.exit('[rel] marker compile failed: ' + r.stderr[-400:])
    link_order += [os.path.join(O, prefix + '_mark_b.o')] + [objname(prefix, u) for u in units] + [os.path.join(O, prefix + '_mark_e.o')]
    table.append((d, prefix))

with open(os.path.join(O, 'rel_table.c'), 'w') as f:
    f.write('// generated by gamecube/native/rel_build.py\n')
    for d, p in table:
        f.write('extern void %s_ObjectSetup(void);\nextern char __%s_data_b[], __%s_data_e[], __%s_bss_b[], __%s_bss_e[];\n' % (p, p, p, p, p))
    f.write('typedef struct { const char* name; void (*setup)(void); char *db, *de, *bb, *be; } RelEntry;\n')
    f.write('const RelEntry mp4web_rel_table[] = {\n')
    for d, p in table:
        f.write('  { "%s", %s_ObjectSetup, __%s_data_b, __%s_data_e, __%s_bss_b, __%s_bss_e },\n' % (d, p, p, p, p, p))
    f.write('  { 0, 0, 0, 0, 0, 0 }\n};\n')
r = run([EMCC] + CFLAGS + ['-c', os.path.join(O, 'rel_table.c'), '-o', os.path.join(O, 'rel_table.o')])
if r.returncode:
    sys.exit('[rel] table compile failed: ' + r.stderr[-600:])
link_order.append(os.path.join(O, 'rel_table.o'))
with open(os.path.join(O, 'link_order.txt'), 'w') as f:
    f.write('\n'.join(link_order) + '\n')
print('[rel] %d overlays compiled in, %d failed' % (len(table), problems))
