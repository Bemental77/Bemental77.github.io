#!/usr/bin/env python3
# Generates src/game/daily_lib.inc.h (in the sm64-port tree) from the behaviour inventory:
# every platform / hazard / mechanism the inventory marks usable as-is, with the model -> geo the
# levels load it with and the behaviour params it is placed with.
#   python3 gen_lib.py <sm64-port dir> <inventory dir with spec_*.json + placed.json>
import json, re, glob, sys, os
root, inv = sys.argv[1], sys.argv[2]
os.chdir(root)
spec = []
for f in sorted(glob.glob(os.path.join(inv, 'spec_*.json'))): spec += json.load(open(f))
placed = json.load(open(os.path.join(inv, 'placed.json')))
pat = re.compile(r'LOAD_MODEL_FROM_GEO\(\s*(?:/\*model\*/\s*)?(\w+)\s*,\s*(?:/\*geo\*/\s*)?(\w+)\s*\)')
m2g = {}
for f in glob.glob('levels/*/script.c') + ['levels/scripts.c']:
    lvl = f.split('/')[1]
    for a, b in pat.findall(open(f).read()): m2g.setdefault(a, []).append(b)
g2h = {}
for h in glob.glob('levels/*/header.h') + glob.glob('actors/*.h'):
    for g in re.findall(r'extern const GeoLayout (\w+)\[\]', open(h).read()): g2h.setdefault(g, h)
behs = set(re.findall(r'^extern const BehaviorScript (bhv\w+)\[\]', open('include/behavior_data.h').read(), re.M))
skip = {'bhvTree', 'bhvDoor', 'bhvTowerDoor', 'bhvCannon', 'bhvGiantPole', 'bhvFloorSwitchHiddenObjects', 'bhvKickableBoard',
        'bhvPushableMetalBox', 'bhvLllRotatingBlockWithFireBars', 'bhvCirclingAmp', 'bhvBowserBomb'}   # handled by their own modules
rows, headers, miss, seen = [], set(), [], set()
for s in spec:
    if s['beh'] in seen: continue
    seen.add(s['beh'])
    b = s['beh']
    if s['category'] not in ('platform', 'hazard', 'mechanism') or s['usable'] != 'yes' or b in skip: continue
    if b not in behs: miss.append((b, 'no beh')); continue
    pm = placed.get(b, {}).get('models', [])
    model = next((x for x in pm if x in m2g), None)
    if not model: miss.append((b, 'model ' + ','.join(pm))); continue
    geo = next((g for g in m2g[model] if g in g2h), None)
    if not geo: miss.append((b, 'geo ' + ','.join(m2g[model]))); continue
    bps = placed.get(b, {}).get('bps', [])
    rows.append((b, geo, bps[0] if bps else '0x00000000', {'platform': 0, 'hazard': 1, 'mechanism': 2}[s['category']], model)); headers.add(g2h[geo])
out = ['// GENERATED by sm64daily/gen_lib.py from the behaviour inventory. Do not edit by hand.',
       '// Every platform, hazard and mechanism SM64 places in its levels that works on its own, with the geo',
       '// and behaviour params it is placed with in its home level. daily.c measures each from the collision',
       '// its own behaviour script loads (LOAD_COLLISION_DATA), and each seed draws its own set from it.']
out += ['#include "%s"' % h for h in sorted(headers)]
out += ['struct AutoPiece { const char *name; const BehaviorScript *beh; const GeoLayout *geo; u32 bp; u8 role; u8 model; };',
        'static const struct AutoPiece sAuto[] = {']
out += ['    { "%s", %s, %s, %s, %d, %s },' % (b[3:], b, g, bp, r, m) for b, g, bp, r, m in rows]
out += ['};', '#define NUM_AUTO ((s32) (sizeof(sAuto) / sizeof(sAuto[0])))']
open('src/game/daily_lib.inc.h', 'w').write('\n'.join(out) + '\n')
print(len(rows), 'pieces:', sum(r[3] == 0 for r in rows), 'platforms,', sum(r[3] == 1 for r in rows), 'hazards,', sum(r[3] == 2 for r in rows), 'mechanisms')
print('not table-able (need their own module):', miss)
