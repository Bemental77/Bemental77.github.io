#!/usr/bin/env python3
# Generates src/game/daily_isles.inc.h (in the sm64-port tree): every area of every SM64 level as a
# spawnable "mini world" — a plain GeoLayout holding the area's own display lists (no skybox, no
# camera) and the area's own collision. daily.c spawns them scaled down as islands in the sky.
#   python3 gen_isles.py <sm64-port dir>
import re, glob, sys, os
os.chdir(sys.argv[1])
rows, out = [], []
for script in sorted(glob.glob('levels/*/script.c')):
    lvl = script.split('/')[1]
    if lvl in ('intro', 'menu', 'ending', 'entry'): continue
    src = open(script).read()
    hdr = 'levels/%s/header.h' % lvl
    if not os.path.exists(hdr): continue
    hsrc = open(hdr).read()
    for m in re.finditer(r'AREA\(\s*(?:/\*index\*/\s*)?(\d+)\s*,\s*(?:/\*geo\*/\s*)?(\w+)\s*\)(.*?)END_AREA', src, re.S):
        n, geo, body = m.group(1), m.group(2), m.group(3)
        tm = re.search(r'TERRAIN\(\s*(?:/\*terrainData\*/\s*)?(\w+)\s*\)', body)
        if not tm: continue
        col = tm.group(1)
        if 'const Collision %s[]' % col not in hsrc: continue
        g = None
        for f in glob.glob('levels/%s/areas/%s/geo.inc.c' % (lvl, n)) + glob.glob('levels/%s/areas/*/geo.inc.c' % lvl) + glob.glob('levels/%s/geo.inc.c' % lvl):
            t = open(f).read()
            m = re.search(r'const GeoLayout %s\[\] = \{(.*?)\n\};' % geo, t, re.S)
            if m: g = m.group(1); break
        if not g: continue
        dls = re.findall(r'GEO_DISPLAY_LIST\(\s*(\w+)\s*,\s*(\w+)\s*\)', g)
        dls = [(l, d) for l, d in dls if d in hsrc]
        if not dls: continue
        name = '%s_%s' % (lvl, n)
        out.append('static const GeoLayout sIsleGeo_%s[] = {\n    GEO_CULLING_RADIUS(32000), GEO_OPEN_NODE(),\n%s\n    GEO_CLOSE_NODE(), GEO_END() };' %
                   (name, '\n'.join('        GEO_DISPLAY_LIST(%s, %s),' % (l, d) for l, d in dls)))
        rows.append((name, col, lvl))
incs = sorted({'levels/%s/header.h' % r[2] for r in rows})
text = ['// GENERATED by sm64daily/gen_isles.py: every level area as a spawnable mini world. Do not edit by hand.']
text += ['#include "%s"' % h for h in incs]
text += out
text += ['struct Isle { const char *name; const GeoLayout *geo; const Collision *col; };', 'static const struct Isle sIsles[] = {']
text += ['    { "%s", sIsleGeo_%s, %s },' % (n.upper(), n, c) for n, c, l in rows]
text += ['};', '#define NUM_ISLES ((s32) (sizeof(sIsles) / sizeof(sIsles[0])))']
open('src/game/daily_isles.inc.h', 'w').write('\n'.join(text) + '\n')
print(len(rows), 'level areas:', ' '.join(r[0] for r in rows))
